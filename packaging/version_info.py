"""Write the Windows version resource for the exe (O-010, Phase 5).

Run by ``packaging\\build.ps1`` with the build venv's Python, after the
project is installed there, so the version is the one being packaged:

    python packaging\\version_info.py OUTPUT_FILE [--commit SHA] [--dirty]

The file is PyInstaller's text form of ``VSVersionInfo``; the specs read its
path from ``STAMPER_VERSION_FILE`` (``spec_common.VERSION_FILE``). It is what
Explorer shows under Properties > Details, and gives antivirus and AppLocker
a product name and version to go by. Agency-neutral: no agency name.
"""

from __future__ import annotations

import argparse
import re
from importlib.metadata import version
from pathlib import Path

PRODUCT = "Document Stamper"
EXE = "DocumentStamper.exe"
VS_FF_PRERELEASE = 0x2
VS_FF_PRIVATEBUILD = 0x8


def numeric(ver: str) -> tuple[int, int, int, int]:
    """``0.1.0.dev0`` -> (0, 1, 0, 0): the first three release numbers, then 0."""
    m = re.match(r"(\d+)(?:\.(\d+))?(?:\.(\d+))?", ver)
    if not m:
        raise SystemExit(f"can't read a version number from {ver!r}")
    parts = [int(p or 0) for p in m.groups()]
    return (*parts, 0)  # type: ignore[return-value]


def render(ver: str, commit: str, dirty: bool) -> str:
    nums = numeric(ver)
    flags = 0
    if re.search(r"(dev|a|b|rc)\d*", ver):
        flags |= VS_FF_PRERELEASE
    if dirty:
        flags |= VS_FF_PRIVATEBUILD
    build = commit[:12] if commit else "unknown"
    if dirty:
        build += " (uncommitted changes)"
    strings = {
        "CompanyName": "Document Stamper project",
        "FileDescription": PRODUCT,
        "FileVersion": ver,
        "InternalName": "DocumentStamper",
        "LegalCopyright": "AGPL-3.0-or-later",
        "OriginalFilename": EXE,
        "ProductName": PRODUCT,
        "ProductVersion": ver,
        "Comments": f"Single-file build. Source commit {build}.",
    }
    if dirty:
        strings["PrivateBuild"] = "Built from a working tree with uncommitted changes"
    table = ",\n        ".join(f"StringStruct({k!r}, {v!r})" for k, v in strings.items())
    return f"""# Generated by packaging/version_info.py; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums!r},
    prodvers={nums!r},
    mask=0x3f,
    flags={flags:#x},
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        {table}
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("output", type=Path)
    ap.add_argument("--commit", default="")
    ap.add_argument("--dirty", action="store_true")
    args = ap.parse_args()
    ver = version("document-stamper")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(ver, args.commit, args.dirty), encoding="utf-8")
    print(ver)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
